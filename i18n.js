function applyI18n() {
    document.documentElement.lang = currentFleetLang();
    applyStaticI18n();
    applyAttrI18n();
    applyTextI18n();
}

// carino-lang.js is deferred and runs before this (also deferred, later in the
// document), so CarinoLang exists by DOMContentLoaded.
document.addEventListener('DOMContentLoaded', applyI18n);
window.addEventListener('carino:langchange', applyI18n);

// Modules (js/app.js and the widgets) reach t() through this handle.
window.CarinoI18n = { t, apply: applyI18n };
