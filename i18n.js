// Elements the app fills from JS at boot (with t() applied). Re-translated here
// on a language switch; skipped while still empty so boot keeps ownership.
const DISCLAIMER_KEY = 'Not investment advice. Quotes may be delayed and come from third-party APIs using your own keys. '
    + 'Alerts fire only while a tab is open. Your watchlist, holdings, rules and keys stay in your browser and are never '
    + 'sent anywhere but the data provider. Stocks is a monitoring and visualization tool only — it does not place trades, '
